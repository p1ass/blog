// AI が好んで使う定型の言い回し。
//
// このファイルの語は、他の 2 つと違ってコーパスでの裏付けがない。手元のコーパス
// (AI が書いた文章 27,391 トークン / 既存 77 記事 89,672 トークン) では両方 0 件
// だった。AI の癖として先回りで入れている。
//
// 既存の preset-ai-writing と preset-ja-technical-writing がすでに拾う言い回し
// (誇張表現、「〜することが可能」など) は入れない。同じ箇所で 2 種類の指摘が出る
// のを避ける。
//
// 助動詞や助詞をまたぐため、辞書はトークン列で書く。同じ言い回しでも漢字とかなで
// 分かち書きが変わるものは、別のエントリに分ける。
//
// 読点の打ち方は textlint/rules/short-topic-comma.cjs で見ている。辞書は
// 「文頭から何文字目か」を条件にできず、ここに書くと長い条件節の読点まで当たる。

// 固定の言い回しは、語の並びそのものが十分に特徴的なので表層形だけで照合する。
// 品詞を指定すると、かえって取りこぼす。「なら」は文脈によって 助動詞「だ」の仮定形
// にも 動詞「なる」の未然形にもなり、句点の有無だけで解析結果が変わる。
// 品詞で絞る必要があるのは、他の語と紛れる単語 (効く / 有効) のほうだけ。
const ni = { pos: '助詞', pos_detail_1: '格助詞', surface_form: 'に' }
const s = surfaceForm => ({ surface_form: surfaceForm })
// この記事の本文はですます体なので、否定は「ない」と「ません」の両方が現れる。
const negative = { surface_form: ['ない', 'ませ'] }

module.exports = [
  {
    // いずれ[名詞/代名詞] + も[助詞/係助詞]。AI 4 : 自分 0 で、ここだけ実測がある。
    message:
      '"いずれも" は硬い表現です。"どちらも" "3 つとも" のように、何を指しているかを書けないか検討してください。',
    tokens: [
      { pos: '名詞', pos_detail_1: '代名詞', basic_form: 'いずれ' },
      { pos: '助詞', pos_detail_1: '係助詞', surface_form: 'も' },
    ],
  },
  {
    // に + 他 + なら + ない。「他なりません」の形も拾うため、末尾は配列で書く。
    message:
      '"〜に他ならない" は大げさな言い回しです。"〜だ" と言い切れないか検討してください。',
    tokens: [ni, s('他'), { surface_form: ['なら', 'なり'] }, negative],
  },
  {
    // かなで書くと「ほかなら」が 1 トークンになり、並びが変わる。
    message:
      '"〜にほかならない" は大げさな言い回しです。"〜だ" と言い切れないか検討してください。',
    tokens: [ni, { surface_form: ['ほかなら', 'ほかなり'] }, negative],
  },
  {
    message:
      '"〜のみならず" は硬い表現です。"〜だけでなく" に言い換えられないか検討してください。',
    tokens: [s('のみ'), s('なら'), s('ず')],
  },
  {
    message:
      '"〜という点で" は回りくどい言い回しです。何がどうなのかを直接書けないか検討してください。',
    tokens: [s('という'), s('点'), s('で')],
  },
  {
    // 漢字とかなの両方に当てるため、surface_form に配列を渡す。
    message:
      '"〜に過ぎない" は大げさな言い回しです。"〜だけだ" に言い換えられないか検討してください。',
    tokens: [ni, { surface_form: ['過ぎ', 'すぎ'] }, negative],
  },
]
