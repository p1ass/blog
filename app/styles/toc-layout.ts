// 目次を本文の右に置いたときの、ページの組み方。
//
// 記事ページと、ヘッダーやフッターの両方が参照する値なので、ここに 1 つ置く。
// どちらか片方で決めると、寄せる量が食い違ってページの中心が 2 本になる。

import { contentWidth } from './breakpoint'
import { space } from './spacing'

// 本文と目次を合わせた組みの外に、最低これだけ残す余白。
// 画面の端に文字が貼り付かない程度に取る。body の左右の 16px より広くしてあるのは、
// 目次が右端に来るためで、16px だと画面の縁と目次の文字が近すぎる。
const minGutter = space['2xl']

// 目次の幅。画面から本文と間隔と左右の余白を引いた残りで、上限は 320px。
//
// 上限を置くのは、広い画面で目次だけが伸び続けるのを避けるため。本文が 760px なので、
// これ以上広げると目次が本文の半分近い面積を占め、添えものに見えなくなる。
//
// 100vw は縦スクロールバーのぶんを含む。余白を 48px 取っているので、バーがある環境でも
// 実際の余白が 40px を下回らず、右へはみ出すこともない。
// 1080px の画面では 200px、1200px 以上では上限の 320px になる。
export const tocWidth = `min(320px, calc(100vw - ${contentWidth} - ${space.lg} - ${minGutter} * 2))`

// 目次を出すページで、中身を左へ寄せる量。
//
// 目次のぶんページの中身は右へ広がる。本文だけを中央に置くと、左の余白が目次の幅ぶん広くなり、
// ページ全体が右へ寄って見える。本文と目次をひとまとまりと見て、その中央をページの中央に合わせる。
// 寄せる量は、目次の幅と本文との間隔を足した半分になる。
//
// 寄せるのは記事の本文だけではない。ヘッダーのサイト名も、記事のタイトルも、フッターも同じだけ
// 動かす。中央に置いた文字がページごとに別の中心を持つと、上から下まで軸が揃わない。
export const tocOffset = `calc((${tocWidth} + ${space.lg}) / 2)`
